#!/usr/bin/env python3
"""Portable purchase allowlists from the owning analytics registry (no network)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDS = ('paywallViewed', 'allowanceReached', 'allowanceBlockShown', 'upgradeTapped',
       'checkoutOpened', 'checkoutCompleted', 'restoreAttempted', 'restoreResult')
TS_PATHS = ('web/app/src/lib/analytics/purchaseContract.generated.ts',
            'desktop/windows/src/renderer/src/lib/purchaseContract.generated.ts')
SWIFT = 'desktop/macos/Desktop/Sources/Generated/PurchaseContract.generated.swift'


def render(doc):
    events = {e['id']: e for e in doc['events'] if e['id'] in IDS}
    assert set(events) == set(IDS)
    specs = {}
    for key, event in events.items():
        assert event['wire_name'].startswith('Subscription ')
        specs[key] = {'name': event['wire_name'], 'properties': {}}
        for prop in event['properties'].values():
            assert prop['type'] == 'enum'  # New purchase dimensions are closed, never content.
            specs[key]['properties'][prop['wire_name']] = prop['values']
    ts = '// Generated by scripts/generate_purchase_telemetry.py; do not edit.\n'
    ts += 'export const purchaseContract = ' + json.dumps(specs, indent=2) + ' as const;\n'
    ts += '''
export type PurchaseEventId = keyof typeof purchaseContract;
export type PurchaseProperties<E extends PurchaseEventId> = {
  [K in keyof typeof purchaseContract[E]['properties']]:
    typeof purchaseContract[E]['properties'][K] extends readonly (infer V)[] ? V : never
};

// Project only declared keys. Unknown values collapse to a declared sentinel.
export function purchasePayload(id: PurchaseEventId, raw: Record<string, unknown>) {
  const spec = purchaseContract[id];
  const properties: Record<string, string> = {};
  for (const [key, values] of Object.entries(spec.properties)) {
    const allowed: readonly string[] = values;
    const value = raw[key];
    if (typeof value === 'string' && allowed.includes(value)) properties[key] = value;
    else if (allowed.includes('unknown')) properties[key] = 'unknown';
  }
  return { name: spec.name, properties };
}

/** One mounted presentation or one authoritative observer, never global account state. */
export class PurchaseObservation {
  private viewed = false;
  private active = new Set<string>();
  constructor(private sink: (id: PurchaseEventId, raw: Record<string, unknown>) => void) {}
  view(raw: Record<string, unknown>) {
    if (this.viewed) return;
    this.viewed = true;
    this.sink('paywallViewed', raw);
  }
  allowance(reached: boolean, raw: Record<string, unknown>, block = false) {
    const id = block ? 'allowanceBlockShown' : 'allowanceReached';
    const safe = purchasePayload(id, raw).properties;
    const key = id + ':' + safe.allowance_kind + ':' + safe.surface;
    if (!reached) { this.active.delete(key); return; }
    if (this.active.has(key)) return;
    this.active.add(key);
    this.sink(id, safe);
  }
}
'''
    swift = '// Generated by scripts/generate_purchase_telemetry.py; do not edit.\n'
    swift += 'enum PurchaseEvent: String {\n'
    swift += ''.join(f'  case {key} = {json.dumps(e["name"])}\n' for key, e in specs.items()) + '}\n'
    swift += 'enum PurchaseContract {\n  static func properties(_ event: PurchaseEvent, _ raw: [String: String]) -> [String: String] {\n    let fields: [String: [String]]\n    switch event {\n'
    for key, event in specs.items():
        fields = ', '.join(json.dumps(k) + ': ' + json.dumps(v) for k, v in event['properties'].items())
        swift += f'    case .{key}: fields = [{fields}]\n'
    swift += '''    }
    var result: [String: String] = [:]
    for (key, allowed) in fields {
      let value = raw[key] ?? "unknown"
      if allowed.contains(value) { result[key] = value }
      else if allowed.contains("unknown") { result[key] = "unknown" }
    }
    return result
  }
}
'''
    return {**{path: ts for path in TS_PATHS}, SWIFT: swift}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    outputs = render(json.loads((ROOT / 'contracts/analytics/events.json').read_text()))
    for path, content in outputs.items():
        target = ROOT / path
        if args.write:
            target.write_text(content)
        elif not target.exists() or target.read_text() != content:
            raise SystemExit(f'{path}: stale; run python3 scripts/generate_purchase_telemetry.py --write')
    print('Purchase telemetry portable contracts current')


if __name__ == '__main__':
    main()
