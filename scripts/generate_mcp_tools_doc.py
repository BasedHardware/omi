#!/usr/bin/env python3
"""Generate the MCP tool inventory in docs/doc/developer/mcp/tools.mdx.

Parses `ToolSpec` entries in backend/utils/mcp_server/registry.py with `ast`
(no imports, no backend dependencies, no network) so the docs page cannot
drift from the tool registry.

Usage:
  python3 scripts/generate_mcp_tools_doc.py            # rewrite the generated block
  python3 scripts/generate_mcp_tools_doc.py --check    # exit 1 with a diff on drift
"""

from __future__ import annotations

import ast
import difflib
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
REGISTRY = REPO / "backend" / "utils" / "mcp_server" / "registry.py"
DOC = REPO / "docs" / "doc" / "developer" / "mcp" / "tools.mdx"

BEGIN = "{/* BEGIN GENERATED:mcp-tools */}"
END = "{/* END GENERATED:mcp-tools */}"

# Tools excluded from the advertised `tools/list` by default (feature-flagged
# off in backend/utils/mcp_server/transport.py). Documented separately, if at all.
EXCLUDED = {"process_recent_conversations"}


def const_str(node: ast.AST | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def parse_specs() -> list[dict[str, str]]:
    tree = ast.parse(REGISTRY.read_text())
    specs: list[dict[str, str]] = []
    for node in ast.walk(tree):
        # TOOL_SPECS: Tuple[ToolSpec, ...] = ( ToolSpec(...), ... )
        if isinstance(node, ast.AnnAssign):
            targets = [node.target] if isinstance(node.target, ast.Name) else []
        elif isinstance(node, ast.Assign):
            targets = node.targets
        else:
            continue
        names = [t.id for t in targets if isinstance(t, ast.Name)]
        if names != ["TOOL_SPECS"] or not isinstance(node.value, ast.Tuple):
            continue
        for element in node.value.elts:
            if not (isinstance(element, ast.Call) and element.keywords):
                continue
            entry: dict[str, str] = {}
            for kw in element.keywords:
                value = const_str(kw.value)
                if value is not None and kw.arg in ("name", "title", "description", "scope"):
                    entry[kw.arg] = " ".join(value.split())
            if entry.get("name"):
                specs.append(entry)
    if not specs:
        raise SystemExit(f"no TOOL_SPECS entries found in {REGISTRY}")
    return specs


def render(specs: list[dict[str, str]]) -> str:
    rows = ["| Tool | Description | Scope |", "| --- | --- | --- |"]
    for spec in specs:
        if spec["name"] in EXCLUDED:
            continue
        description = spec.get('description', '').replace('|', '\\|')
        rows.append(f"| `{spec['name']}` | {description} | `{spec.get('scope', '')}` |")
    excluded_note = (
        "\n\nExcluded from this table (feature-flagged off and not advertised in "
        "`tools/list` by default): "
        + ", ".join(f"`{n}`" for n in sorted(EXCLUDED)) + ".\n"
    )
    return (
        f"{BEGIN}\n"
        "{/* Generated by scripts/generate_mcp_tools_doc.py from TOOL_SPECS in\n"
        "backend/utils/mcp_server/registry.py. Edit the script or the registry, not this block. */}\n\n"
        + "\n".join(rows)
        + excluded_note
        + f"{END}"
    )


def main() -> int:
    block = render(parse_specs())
    text = DOC.read_text()
    if BEGIN in text and END in text:
        head = text.split(BEGIN)[0]
        tail = text.split(END)[1]
        new = head + block + tail
    else:
        # First run: insert after the intro, before the first "## Memory Tools" heading.
        marker = "## Memory Tools"
        if marker not in text:
            raise SystemExit("insertion marker '## Memory Tools' not found in tools.mdx")
        head, tail = text.split(marker, 1)
        new = head + block + "\n\n---\n\n" + marker + tail
    if "--check" in sys.argv:
        if new == text:
            print("mcp tools doc: up to date")
            return 0
        diff = difflib.unified_diff(text.splitlines(True), new.splitlines(True),
                                    fromfile=str(DOC), tofile=str(DOC) + " (expected)")
        sys.stdout.writelines(diff)
        return 1
    DOC.write_text(new)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
