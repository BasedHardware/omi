#!/usr/bin/env python3
"""Generate the checkout currency display table from ICU (Node Intl.NumberFormat).

Stripe Checkout renders an amount with the browser's Intl.NumberFormat in the session
locale. The server pins that locale per currency (utils/local_currency.checkout_locale:
`en-GB` for USD, `en` otherwise), so this script renders every Stripe currency the same
way and writes the symbol prefix, display decimals and a sample string to:

- backend/config/checkout_currency_format.json (server: utils/local_currency.display_money)
- app/lib/utils/checkout_currency_format.dart (app: utils/billing_price.formatBillingPrice)

Both formatters are tested against the samples. Requires `node` with full ICU.
Usage: generate_checkout_currency_format.py [--check]
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JSON_OUT = ROOT / 'backend/config/checkout_currency_format.json'
DART_OUT = ROOT / 'app/lib/utils/checkout_currency_format.dart'

# Stripe presentment currencies (https://docs.stripe.com/currencies).
CURRENCIES = (
    'usd aed afn all amd ang aoa ars aud awg azn bam bbd bdt bgn bhd bif bmd bnd bob brl bsd bwp byn bzd cad '
    'cdf chf clp cny cop crc cve czk djf dkk dop dzd egp etb eur fjd fkp gbp gel gip gmd gnf gtq gyd hkd hnl '
    'htg huf idr ils inr isk jmd jod jpy kes kgs khr kmf krw kwd kyd kzt lak lbp lkr lrd lsl mad mdl mga mkd '
    'mmk mnt mop mur mvr mwk mxn myr mzn nad ngn nio nok npr nzd omr pab pen pgk php pkr pln pyg qar ron rsd '
    'rub rwf sar sbd scr sek sgd shp sle sos srd szl thb tjs tnd top try ttd twd tzs uah ugx uyu uzs vnd vuv '
    'wst xaf xcd xof xpf yer zar zmw'
).split()
# Stripe charge units (minor-unit exponent), not CLDR display decimals.
ZERO_DECIMAL = set('bif clp djf gnf jpy kmf krw mga pyg rwf vnd vuv xaf xof xpf'.split())
THREE_DECIMAL = set('bhd jod kwd omr tnd'.split())
SAMPLE_MINOR = 1234500

NODE = r"""
const [codes, zero, three, sample] = JSON.parse(process.argv[1]);
const out = {};
for (const code of codes) {
  const locale = code === 'usd' ? 'en-GB' : 'en';
  const fmt = new Intl.NumberFormat(locale, {style: 'currency', currency: code.toUpperCase()});
  const parts = fmt.formatToParts(1234.5);
  const first = parts.findIndex(p => p.type === 'integer');
  if (first < 0 || parts.slice(0, first).some(p => !['currency', 'literal'].includes(p.type))) throw new Error(code);
  if (parts.slice(first).some(p => p.type === 'currency')) throw new Error('suffix symbol ' + code);
  const exponent = zero.includes(code) ? 0 : (three.includes(code) ? 3 : 2);
  out[code] = {
    locale,
    prefix: parts.slice(0, first).map(p => p.value).join(''),
    digits: fmt.resolvedOptions().maximumFractionDigits,
    stripe_exponent: exponent,
    sample_minor: sample,
    sample: fmt.format(sample / 10 ** exponent),
  };
}
console.log(JSON.stringify({icu: process.versions.icu, cldr: process.versions.cldr, currencies: out}));
"""


def render() -> dict:
    args = json.dumps([CURRENCIES, sorted(ZERO_DECIMAL), sorted(THREE_DECIMAL), SAMPLE_MINOR])
    result = subprocess.run(['node', '-e', NODE, args], check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def _dart_string(value: str) -> str:
    escaped = value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    return "'" + ''.join(c if c.isprintable() and c != '\u00a0' else f'\\u{ord(c):04x}' for c in escaped) + "'"


def dart(table: dict) -> str:
    rows = ''.join(
        f"  '{code}': ({_dart_string(row['prefix'])}, {row['digits']}, {row['stripe_exponent']}),\n"
        for code, row in table['currencies'].items()
    )
    return (
        '// GENERATED by backend/scripts/generate_checkout_currency_format.py. Do not edit.\n'
        '//\n'
        '// How Stripe Checkout renders each currency at the server-pinned locale (en-GB for USD,\n'
        "// en otherwise), from ICU Intl.NumberFormat: (symbol prefix, display decimals, Stripe\n"
        '// minor-unit exponent). The app formats purchase amounts with it so the offer page and\n'
        f"// the cart show the same string. ICU {table['icu']}, CLDR {table['cldr']}.\n\n"
        'const checkoutCurrencyFormat = <String, (String, int, int)>{\n'
        f'{rows}'
        '};\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    table = render()
    outputs = {JSON_OUT: json.dumps(table, indent=2, ensure_ascii=False) + '\n', DART_OUT: dart(table)}
    if args.check:
        stale = [str(path) for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        if stale:
            print('stale: ' + ', '.join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
