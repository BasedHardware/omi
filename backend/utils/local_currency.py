"""Local-currency offers for new buyers (Google Play Subscriptions policy). Default off.

Google Play rejected Android builds because a non-US reviewer saw the trial offer in
US$. This module decides, per request, whether a buyer with no paid subscription is
offered the plan price in a local currency or today's USD price. A country outside the
table keeps USD, as Google Play itself does where it has no local currency.

Two operator inputs, both empty by default, so every response stays as it is today:

- ``STOREFRONT_LOCAL_CURRENCY``: ``off`` (default), ``android`` or ``all``.
- ``STOREFRONT_LOCAL_CURRENCY_TABLE``: JSON ``{"countries": {"JP": "jpy", "GB": "gbp"},
  "currencies": {"jpy": {"monthly": 4800, "annual": 43200}, "gbp": {"monthly": 2299,
  "annual": 20699}}}``. Countries are ISO 3166-1 alpha-2, currencies ISO 4217 lowercase,
  amounts Stripe minor units (JPY 4800 is ¥4,800; HUF/TWD/ISK/UGX in hundredths and
  whole hundreds). They are the operator's approval, not the display source.

Stripe stays the price authority (plan-source-of-truth.md): a local amount is the
Price's own ``currency_options`` entry, shown only when it equals the approved table
amount. Checkout charges that same entry, so the cart matches the offer page.

The country is the device region the app sends in ``X-Omi-Storefront-Region``. A
request without it (every released build) keeps today's behaviour.
"""

import json
import logging
import os
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from decimal import Decimal, ROUND_HALF_UP
from typing import Any, Callable, Literal, Mapping, Optional

logger = logging.getLogger(__name__)

REGION_HEADER = 'X-Omi-Storefront-Region'
MODE_ENV = 'STOREFRONT_LOCAL_CURRENCY'
TABLE_ENV = 'STOREFRONT_LOCAL_CURRENCY_TABLE'
MODES = ('off', 'android', 'all')
INTERVAL_KEYS = {'month': 'monthly', 'year': 'annual'}

_REGION = re.compile(r'^[A-Z]{2}$')
_CURRENCY = re.compile(r'^[a-z]{3}$')

# Stripe requires these amounts in whole hundreds (https://docs.stripe.com/currencies#special-cases).
WHOLE_HUNDREDS = frozenset({'huf', 'twd', 'isk', 'ugx'})
FORMAT_TABLE = Path(__file__).resolve().parents[1] / 'config/checkout_currency_format.json'


@lru_cache(maxsize=1)
def checkout_formats() -> dict[str, dict[str, Any]]:
    """How Stripe Checkout renders each currency at its pinned locale (ICU; generated by
    scripts/generate_checkout_currency_format.py and shared with the app)."""
    return json.loads(FORMAT_TABLE.read_text())['currencies']


@dataclass(frozen=True)
class Table:
    countries: dict[str, str]
    amounts: dict[str, dict[str, int]]


@dataclass(frozen=True)
class Offer:
    """``default``: today's behaviour (USD). ``local``: the price in ``currency``."""

    kind: Literal['default', 'local']
    currency: Optional[str] = None

    @property
    def is_default(self) -> bool:
        return self.kind == 'default'


DEFAULT = Offer('default')


def mode() -> str:
    raw = (os.getenv(MODE_ENV) or 'off').strip().lower()
    return raw if raw in MODES else 'off'


def load_table() -> Table:
    """Parse the operator table. Anything malformed is dropped, never guessed."""
    raw = (os.getenv(TABLE_ENV) or '').strip()
    if not raw:
        return Table({}, {})
    try:
        payload = json.loads(raw)
    except ValueError:
        logger.warning('%s is not JSON; local currency stays off', TABLE_ENV)
        return Table({}, {})
    if not isinstance(payload, dict):
        return Table({}, {})
    amounts: dict[str, dict[str, int]] = {}
    for currency, row in (payload.get('currencies') or {}).items():
        if not isinstance(currency, str) or not _CURRENCY.fullmatch(currency) or not isinstance(row, dict):
            continue
        values = {key: row.get(key) for key in INTERVAL_KEYS.values()}
        if all(_valid_amount(currency, value) for value in values.values()):
            amounts[currency] = values  # type: ignore[assignment]
        else:
            logger.warning('local currency table: %s amounts rejected', currency)
    countries: dict[str, str] = {}
    for country, currency in (payload.get('countries') or {}).items():
        if not isinstance(country, str) or not _REGION.fullmatch(country) or not isinstance(currency, str):
            continue
        if currency == 'usd' or currency in amounts:
            countries[country] = currency
    return Table(countries, amounts)


def _valid_amount(currency: str, value: Any) -> bool:
    """A positive Stripe amount the cart can show exactly in ``currency``."""
    fmt = checkout_formats().get(currency)
    if fmt is None or type(value) is not int or value <= 0:
        return False
    if currency in WHOLE_HUNDREDS and value % 100:
        return False
    # ISK/UGX: Stripe hundredths, no displayed decimals. Never round a charged amount.
    return value % 10 ** max(0, fmt['stripe_exponent'] - fmt['digits']) == 0


def normalize_region(raw: Any) -> Optional[str]:
    if not isinstance(raw, str):
        return None
    value = raw.strip().upper()
    return value if _REGION.fullmatch(value) else None


def offer_for(platform: Any, region: Any) -> Offer:
    """Which offer a buyer with no paid subscription gets, before checking Stripe."""
    selected = mode()
    if selected == 'off':
        return DEFAULT
    normalized_platform = platform.strip().lower() if isinstance(platform, str) else ''
    if selected == 'android' and normalized_platform != 'android':
        return DEFAULT
    country = normalize_region(region)
    if country is None:
        return DEFAULT
    table = load_table()
    if not table.countries or country == 'US':
        return DEFAULT
    currency = table.countries.get(country)
    if currency and currency != 'usd':
        return Offer('local', currency)
    return DEFAULT


def _get(obj: Any, key: str) -> Any:
    if isinstance(obj, Mapping):
        return obj.get(key)
    return getattr(obj, key, None)


def option_amount(price: Any, currency: str) -> Optional[int]:
    """Stripe's ``currency_options[currency].unit_amount``; None when absent."""
    if _get(price, 'currency') == currency:
        amount = _get(price, 'unit_amount')
        return amount if type(amount) is int and amount > 0 else None
    options = _get(price, 'currency_options')
    option = _get(options, currency) if options is not None else None
    amount = _get(option, 'unit_amount') if option is not None else None
    return amount if type(amount) is int and amount > 0 else None


def approved_amount(price: Any, currency: str) -> Optional[int]:
    """The local amount for a new buyer: Stripe's option, only when it equals the table."""
    recurring = _get(price, 'recurring')
    interval = _get(recurring, 'interval') if recurring is not None else None
    key = INTERVAL_KEYS.get(interval) if isinstance(interval, str) else None
    if key is None or _get(price, 'currency') == currency:
        return None
    expected = load_table().amounts.get(currency, {}).get(key)
    amount = option_amount(price, currency)
    if expected is None or amount != expected:
        # A config mistake must never open a Checkout in a currency the Price lacks: USD instead.
        logger.warning(
            'local currency %s unavailable on %s (option %s, table %s); offering USD',
            currency,
            _get(price, 'id'),
            amount,
            expected,
        )
        return None
    return amount


# ISO 4217 "no currency": a subscription whose billed currency could not be read.
UNKNOWN_CURRENCY = 'xxx'


class OptionLookupFailed(Exception):
    """Stripe could not be read, so the billed amount is unknown. Callers show nothing."""


def billed_option_amount(
    price: Any, subscription_currency: Any, retrieve: Optional[Callable[[str], Any]] = None
) -> Optional[int]:
    """What Stripe bills a subscription in ``subscription_currency`` on ``price``.

    Decided from Stripe alone, never from the switch or the operator table, so a rollback
    or table edit cannot change what an existing subscriber is told. A subscription on a
    multi-currency Price carries the base Price on its item, and Stripe bills the Price's
    ``currency_options[subscription_currency]``. None when the subscription is in the
    Price's own currency or the Price has no such option (older Adaptive Pricing
    conversions keep today's handling). Raises OptionLookupFailed when the Price cannot
    be read.
    """
    base = _get(price, 'currency')
    if not isinstance(subscription_currency, str) or not isinstance(base, str) or base == subscription_currency:
        return None
    amount = option_amount(price, subscription_currency)
    price_id = _get(price, 'id')
    if amount is not None or _get(price, 'currency_options') is not None or not isinstance(price_id, str):
        return amount
    try:
        expanded = (retrieve or retrieve_with_options)(price_id)
    except Exception as exc:
        logger.warning('currency option lookup failed: %s', type(exc).__name__)
        raise OptionLookupFailed(price_id) from exc
    return option_amount(expanded, subscription_currency)


def foreign_options(price: Any) -> set[str]:
    """Currencies other than the Price's own in its expanded ``currency_options``."""
    options = _get(price, 'currency_options') or {}
    keys = options.keys() if isinstance(options, Mapping) else []
    return {code for code in keys if code != _get(price, 'currency')}


def buyer_currency(platform: Any, region: Any, customer_currency: Any, prices: list[Any]) -> Optional[str]:
    """The currency to show and charge a buyer with no paid plan; None for the Price's own (USD).

    ``prices`` are the offered Prices with ``currency_options`` expanded. A Stripe customer
    that already has a currency can only be charged in it, so it wins over the region: a
    USD customer stays in USD, a customer in another currency gets that currency when
    every offered Price carries it (else today's USD path). Otherwise the region's
    approved table currency applies when the live Prices match the table.
    """
    if isinstance(customer_currency, str) and customer_currency:
        if customer_currency == 'usd' or not prices:
            return None
        if all(option_amount(price, customer_currency) is not None for price in prices):
            return customer_currency
        logger.warning('customer currency %s missing on an offered price; offering USD', customer_currency)
        return None
    offer = offer_for(platform, region)
    if offer.kind != 'local' or not offer.currency or not prices:
        return None
    if all(approved_amount(price, offer.currency) is not None for price in prices):
        return offer.currency
    return None


def offer_amount(price: Any, currency: str, customer_currency: Any) -> Optional[int]:
    """The amount for ``buyer_currency``'s choice: the customer's option, or the approved table amount."""
    if customer_currency == currency:
        return option_amount(price, currency)
    return approved_amount(price, currency)


def retrieve_with_options(price_id: str) -> Any:
    """A Stripe Price with its ``currency_options`` (not returned unless expanded)."""
    import stripe

    return stripe.Price.retrieve(price_id, expand=['currency_options'])


PRICE_CACHE_SECONDS = 300


def cached_price_with_options(price_id: str) -> dict[str, Any]:
    """``retrieve_with_options`` as a dict, cached briefly. Options of a live Price are not
    edited in place (scripts/local_currency_options.py refuses), and Checkout re-reads live."""
    from database import redis_db

    key = f'stripe_price_currency_options:{price_id}'
    try:
        cached = redis_db.get_generic_cache(key)
    except Exception:  # noqa: BLE001 - cache is optional
        cached = None
    if isinstance(cached, dict) and cached.get('id') == price_id:
        return cached
    price = retrieve_with_options(price_id)
    row = price.to_dict_recursive() if hasattr(price, 'to_dict_recursive') else dict(price)
    try:
        redis_db.set_generic_cache(key, row, ttl=PRICE_CACHE_SECONDS)
    except Exception:  # noqa: BLE001 - cache is optional
        pass
    return row


@dataclass(frozen=True)
class BuyerOffer:
    """``currency`` None: today's prices. Otherwise ``amounts`` maps each offered Price id to its amount."""

    currency: Optional[str] = None
    amounts: Optional[dict[str, int]] = None
    rows: Optional[dict[str, dict[str, Any]]] = None


def customer_currency(customer_id: Optional[str]) -> Optional[str]:
    """A Stripe customer's fixed recurring currency, or None (no customer, or none set yet)."""
    if not customer_id:
        return None
    import stripe

    currency = getattr(stripe.Customer.retrieve(customer_id), 'currency', None)
    return currency.lower() if isinstance(currency, str) and currency else None


def new_buyer_offer(
    platform: Any,
    region: Any,
    customer_id: Callable[[], Optional[str]],
    price_ids: list[str],
    retrieve: Optional[Callable[[str], Any]] = None,
) -> BuyerOffer:
    """What a buyer with no paid plan is shown and charged (see ``buyer_currency``).

    No Stripe or customer read happens unless a local offer applies or an offered Price
    already carries a non-USD option, so today (USD-only Prices, switch off) nothing changes.
    """
    if not price_ids:
        return BuyerOffer()
    retrieve = retrieve or cached_price_with_options
    local = offer_for(platform, region)
    if local.kind != 'local':
        # Today's path unless an existing customer is fixed to another currency the Prices carry.
        # First-time buyers read nothing; any read failure keeps today's prices.
        customer = customer_id()
        if not customer:
            return BuyerOffer()
        try:
            rows = {price_id: retrieve(price_id) for price_id in price_ids}
            if not any(foreign_options(row) for row in rows.values()):
                return BuyerOffer()
            fixed = customer_currency(customer)
        except Exception as exc:  # noqa: BLE001 - today's prices
            logger.warning('customer currency lookup failed: %s', type(exc).__name__)
            return BuyerOffer()
    else:
        rows = {price_id: retrieve(price_id) for price_id in price_ids}
        fixed = customer_currency(customer_id()) if any(foreign_options(row) for row in rows.values()) else None
    currency = buyer_currency(platform, region, fixed, list(rows.values()))
    if currency is None:
        return BuyerOffer()
    amounts = {price_id: offer_amount(row, currency, fixed) for price_id, row in rows.items()}
    if any(amount is None for amount in amounts.values()):
        return BuyerOffer()
    return BuyerOffer(currency, amounts, rows)  # type: ignore[arg-type]


def checkout_locale(currency: str) -> str:
    """Checkout locale whose currency glyph matches the app for ``currency``.

    `en-GB` renders USD as US$ (#25494). Other currencies use `en`, whose ICU symbols are
    in config/checkout_currency_format.json (`en-GB` would render JPY as JP¥, not ¥).
    """
    return 'en-GB' if currency.lower() == 'usd' else 'en'


def display_money(amount_minor: int, currency: str) -> str:
    """The string Stripe Checkout shows for ``amount_minor`` at checkout_locale(currency).

    Same table as the app's formatBillingPrice: ICU symbol prefix, `en` grouping, the
    currency's display decimals (always shown), Stripe's minor-unit exponent.
    """
    fmt = checkout_formats()[currency.strip().lower()]
    digits = fmt['digits']
    major = Decimal(amount_minor) / (Decimal(10) ** fmt['stripe_exponent'])
    quantizer = Decimal(1) if digits == 0 else Decimal(10) ** -digits
    return f"{fmt['prefix']}{major.quantize(quantizer, rounding=ROUND_HALF_UP):,.{digits}f}"
