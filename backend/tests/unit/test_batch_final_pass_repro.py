def test_diagnostics_never_invoke_custom_exception_stringification():
    from utils.conversations.final_pass_errors import error_details

    class UnsafeMessage(Exception):
        def __str__(self):
            raise AssertionError('exception formatting must not execute')

    try:
        raise UnsafeMessage({'transcript': 'PRIVATE'})
    except UnsafeMessage as error:
        details = error_details(error)
    assert details['reason'] == 'unclassified' and details['exception_type'] == 'UnsafeMessage'
    assert details['location'].endswith(':test_diagnostics_never_invoke_custom_exception_stringification')
    assert 'PRIVATE' not in repr(details)


