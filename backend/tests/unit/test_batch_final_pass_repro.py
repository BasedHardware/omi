def test_more_than_128_registered_units_reach_diarization(multi_unit):
    from uuid import NAMESPACE_URL, uuid5

    rows, ns = multi_unit.client.rows, multi_unit.store.namespace
    prototype = rows[(ns + '_jobs', 'unit-a')]
    for i in range(127):
        unit = f'fragment-{i}'
        rows[(ns + '_jobs', unit)] = {
            **deepcopy(prototype),
            'segment_id': unit,
            'duration_seconds': 1,
            'capture_at': 1200 + i,
            'audio_uri': f'gs://fake/{unit}#1',
        }
        rows[(ns + '_results', unit)] = {
            'projection_parts': {'0': {'conversation_id': 'conversation', 'speaker_scope': f'final:batch:{unit}'}},
            'result': {'result_uri': f'gs://fake/{unit}-result#1'},
        }
        for kind, uri in [('audio', f'gs://fake/{unit}'), ('results', f'gs://fake/{unit}-result')]:
            key = hashlib.sha256(f'{unit}\0{uri}'.encode()).hexdigest()
            rows[(ns + '_artifacts', key)] = dict(
                kind=kind, owner_id=UID, segment_id=unit, privacy_generation=0, uri=uri
            )
        multi_unit.payloads[unit] = {
            'audio_seconds': 1,
            'words': [{'word': 'Unit.', 'timestamp': [0.1, 0.8]}],
            'diarization': {'turns': [{'start': 0, 'end': 1, 'speaker': 'SPEAKER_00'}]},
        }
        multi_unit.lane.conversation.transcript_segments.append(
            TranscriptSegment(
                id=str(uuid5(NAMESPACE_URL, f'batch:{unit}:0')),
                text='Unit.',
                start=2200 + i,
                end=2200.7 + i,
                is_user=False,
                speaker_id=0,
                speaker_id_scope=f'final:batch:{unit}',
            )
        )
    result = replay(multi_unit)
    assert result['outcome'] == 'success', result
    assert result['changed_segments'] == 130
    assert result['segment_coverage']['placed'] == 130


