@pytest.mark.parametrize(
    'reason',
    [
        'no_job',
        'no_result',
        'receipt_missing',
        'artifact_row_missing',
        'generation_mismatch',
        'erasure',
        'uri_mismatch',
        'artifact_kind_mismatch',
        'artifact_owner_mismatch',
        'artifact_unit_mismatch',
    ],
)
def test_reference_refusals_have_specific_safe_codes(multi_unit, reason):
    rows, ns = multi_unit.client.rows, multi_unit.store.namespace
    if reason == 'no_job':
        rows.pop((ns + '_jobs', 'unit-a'))
    elif reason == 'no_result':
        rows.pop((ns + '_results', 'unit-a'))
    elif reason == 'receipt_missing':
        rows[(ns + '_results', 'unit-a')].pop('projection_parts')
    else:
        path = next(path for path, row in rows.items() if path[0] == ns + '_artifacts' and row['kind'] == 'audio')
        if reason == 'artifact_row_missing':
            rows.pop(path)
        else:
            field, value = {
                'generation_mismatch': ('privacy_generation', 9),
                'erasure': ('erasure_requested', True),
                'uri_mismatch': ('uri', 'gs://private-not-logged'),
                'artifact_kind_mismatch': ('kind', 'voice_evidence'),
                'artifact_owner_mismatch': ('owner_id', 'private-not-logged'),
                'artifact_unit_mismatch': ('segment_id', 'private-not-logged'),
            }[reason]
            rows[path][field] = value
    with pytest.raises(references.ReferenceUnavailable) as caught:
        references.load_reference(multi_unit.store, UID, 'unit-a', 'conversation')
    assert str(caught.value) == reason and caught.value.outcome == 'failed_incomplete_coverage'


@pytest.mark.parametrize(
    'kind,reason',
    [
        ('id', 'projection_segment_missing'),
        ('text', 'projection_text_mismatch'),
        ('point', 'projection_point_words'),
        ('eof', 'projection_point_words'),
        ('no_job', 'no_job'),
    ],
)
def test_unplaced_evidence_is_partial_and_keeps_its_labels(multi_unit, monkeypatch, kind, reason):
    segment = multi_unit.lane.conversation.transcript_segments[0]
    if kind == 'id':
        segment.id = 'stored-legacy-projection-id'
    elif kind == 'text':
        segment.text = 'Previously grouped transcript.'
    elif kind in ('point', 'eof'):
        multi_unit.payloads['unit-a']['words'] = [
            {'word': 'Hello there.', 'timestamp': [2, 2] if kind == 'point' else [8.005, 8.009]}
        ]
    else:
        multi_unit.client.rows.pop((multi_unit.store.namespace + '_jobs', 'unit-a'))
    original = segment.model_copy(deep=True)
    monkeypatch.setattr(batch.recurring_voices, 'checkpoint', lambda *a, **kw: ('synthetic',))
    # The lab's captured learning count, rather than an outer mock, proves abstention.
    result = replay(multi_unit)
    assert result['outcome'] == 'partial_coverage', result
    assert result['coverage'] == {'required': 3, 'placed': 2, 'unplaced': 1}
    assert result['coverage_reasons'] == {reason: 1}
    assert result['changed_segments'] == 2 and result['learn_calls'] == 0
    assert multi_unit.lane.conversation.transcript_segments[0] == original
    assert multi_unit.lane.conversation.speaker_resolution.status == 'unavailable'


def test_unknown_error_has_innermost_backend_location_without_private_message(multi_unit, monkeypatch, caplog):
    import logging

    def private_failure(*a, **kw):
        raise AttributeError('PRIVATE transcript or uid must never be logged')

    monkeypatch.setattr(final, 'diarize_with_speech_compaction', private_failure)
    caplog.set_level(logging.INFO)
    result = replay(multi_unit)
    assert result['exception_type'] == 'AttributeError' and result['message'] == 'unclassified'
    assert result['location'].startswith('tests/unit/test_batch_final_pass_repro.py:')
    assert result['location'].endswith(':private_failure')
    assert 'PRIVATE' not in repr(result) + caplog.text
    assert any(
        'event=batch_final_pass ' in record.message and f"location={result['location']}" in record.message
        for record in caplog.records
    )


