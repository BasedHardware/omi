def replay(case):
    return lab.reproduce(UID, case.lane.conversation, {}, load_prints=lambda *a, **kw: {})


def test_real_multi_unit_mixed_authority_reproduce_has_no_attribute_error(multi_unit):
    untouched = [
        s.model_copy(deep=True)
        for s in multi_unit.lane.conversation.transcript_segments
        if s.id in ('sync-segment', '9033d5ea-76fb-5cb7-8988-64c32cbf1e4c')
    ]
    result = replay(multi_unit)
    assert result['exception_type'] != 'AttributeError', result
    assert result['outcome'] == 'success', result
    assert result['changed_segments'] == 3
    assert result['segment_coverage'] == {'total': 5, 'required': 3, 'placed': 3}
    assert [
        s for s in multi_unit.lane.conversation.transcript_segments if s.id in {x.id for x in untouched}
    ] == untouched
    assert multi_unit.client.rows == multi_unit.before
    assert not multi_unit.timer._metrics  # No default-registry children created by the lab.


def test_incomplete_silent_metric_protocol_including_contexts():
    from prometheus_client import Counter, Gauge

    counter = Counter('owner_lab_context_counter', 'Synthetic', ['kind'])
    gauge = Gauge('owner_lab_context_gauge', 'Synthetic', ['kind'])
    histogram = Histogram('owner_lab_context_histogram', 'Synthetic', ['kind'])
    try:
        with lab.isolated_metrics():
            with counter.labels('replay').count_exceptions(ValueError):
                pass
            with gauge.labels('replay').track_inprogress():
                gauge.labels('replay').set_function(lambda: 9)
            with histogram.labels('replay').time():
                assert histogram.labels('replay')._sum.get() == 0
                histogram.labels('replay')._buckets[0].inc(1)
            assert counter.labels('replay')._value.get() == 0
        assert not counter._metrics and not gauge._metrics and not histogram._metrics
    finally:
        for metric in (counter, gauge, histogram):
            REGISTRY.unregister(metric)


