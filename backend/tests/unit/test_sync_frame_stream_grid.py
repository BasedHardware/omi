"""Sync frame-stream grid: every hostile WAL byte-stream shape.

``_frame_count`` walks the strict length-prefixed WAL stream before any
decode. This grid pins its verdict for every stream family the format can
produce: exact size sweep, short-payload sweep, valid multi-frame counts,
every truncation prefix of a real stream, zero/oversize size fields at each
frame position, and trailing partial headers. Every fault is the typed
deterministic family type (``StagedAudioInvalid``); every count is the
verified literal.

Failure-Class: FC-sync-decode-fault-anonymous-at-typed-boundaries
"""

import pathlib
import struct
import tempfile

import pytest

from utils.batch_pipeline.audio import StagedAudioInvalid
from utils.batch_pipeline.capture_decode import _frame_count


def _one_frame(size: int, payload_len: int) -> bytes:
    return struct.pack('<I', size) + b'\x11' * payload_len


def _write(tag: str, data: bytes) -> str:
    root = pathlib.Path(tempfile.mkdtemp(prefix='omi_frame_grid_'))
    path = root / f'{tag}.bin'
    path.write_bytes(data)
    return str(path)


def test_frame_stream_size1_exact() -> None:
    """size field 1 with the exact payload: ok."""
    path = _write("size1_exact", b'\x01\x00\x00\x00\x11')
    assert _frame_count(path) == 1


def test_frame_stream_size1_short() -> None:
    """size field 1 with payload one byte short: invalid sync audio frame."""
    path = _write("size1_short", b'\x01\x00\x00\x00')
    with pytest.raises(StagedAudioInvalid) as caught:
        _frame_count(path)
    assert type(caught.value) is StagedAudioInvalid
    assert str(caught.value) == 'invalid sync audio frame'
    assert isinstance(caught.value, ValueError)


