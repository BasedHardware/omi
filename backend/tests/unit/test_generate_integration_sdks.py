def test_check_rejects_stale_dart_generated_client(monkeypatch, tmp_path):
    monkeypatch.delenv('FLUTTER_ROOT', raising=False)
    monkeypatch.setattr('shutil.which', lambda _: None)
    monkeypatch.setattr(generator, '_format_dart_tree', lambda _: None)
    files = generator.generate_all(generator.DEFAULT_SPEC)
    generator.write_tree(tmp_path, files)

    assert generator.main(['--check', '--out', str(tmp_path)]) == 0
    dart_client = tmp_path / 'dart/lib/omi_integration.g.dart'
    dart_client.write_text('stale\n', encoding='utf-8')

    assert generator.main(['--check', '--out', str(tmp_path)]) == 1
    dart_client.write_text(files['dart/lib/omi_integration.g.dart'], encoding='utf-8')
    dart_barrel = tmp_path / 'dart/lib/omi_integration.dart'
    dart_barrel.write_text('stale\n', encoding='utf-8')

    assert generator.main(['--check', '--out', str(tmp_path)]) == 1


def test_check_formats_expected_dart_tree(monkeypatch, tmp_path):
    def format_dart(root):
        barrel = root / 'dart/lib/omi_integration.dart'
        barrel.write_text(barrel.read_text(encoding='utf-8').replace('library;', 'library;\n'), encoding='utf-8')

    monkeypatch.delenv('FLUTTER_ROOT', raising=False)
    monkeypatch.setattr('shutil.which', lambda _: None)
    monkeypatch.setattr(generator, '_format_dart_tree', format_dart)
    files = generator.generate_all(generator.DEFAULT_SPEC)
    generator.write_tree(tmp_path, files)
    format_dart(tmp_path)

    assert generator.main(['--check', '--out', str(tmp_path)]) == 0


def test_check_rejects_orphan_generated_file(tmp_path):
    files = generator.generate_all(generator.DEFAULT_SPEC)
    generator.write_tree(tmp_path, files)
    orphan = tmp_path / 'go/omiintegration/removed_gen.go'
    orphan.write_text('// AUTO-GENERATED by backend/scripts/generate_integration_sdks.py\n', encoding='utf-8')

    assert generator.main(['--check', '--out', str(tmp_path)]) == 1
