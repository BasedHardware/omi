#!/usr/bin/env node
// Generates the typed shell<->surface bridge for both sides from contract/bridge.json.
// Mirrors the program's generated-over-hand-rolled doctrine (Pigeon precedent).
// Usage: node codegen/generate.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(readFileSync(join(root, "contract", "bridge.json"), "utf8"));
const check = process.argv.includes("--check");

const BANNER = (src) =>
  `// GENERATED by codegen/generate.mjs from contract/bridge.json (v${contract.version}). DO NOT EDIT.\n// Regenerate: node codegen/generate.mjs\n`;

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const SWIFT_SCALARS = { string: "String", int: "Int", double: "Double", bool: "Bool" };
const TS_SCALARS = { string: "string", int: "number", double: "number", bool: "boolean" };

const swiftType = (t, optional) =>
  (SWIFT_SCALARS[t] ?? t) + (optional ? "?" : "");
const tsType = (t) => {
  if (TS_SCALARS[t]) return TS_SCALARS[t];
  return t;
};

/* ---------------------------------- Swift ---------------------------------- */
function swift() {
  const L = [];
  L.push(BANNER());
  L.push("import Foundation\n");

  for (const [name, def] of Object.entries(contract.types)) {
    if (def.kind === "enum") {
      L.push(`public enum ${name}: String, Codable, Sendable {`);
      for (const c of def.cases) L.push(`  case ${c}`);
      L.push("}\n");
    } else {
      L.push(`public struct ${name}: Codable, Sendable {`);
      for (const [f, fd] of Object.entries(def.fields))
        L.push(`  public var ${f}: ${swiftType(fd.type, fd.optional)}`);
      const args = Object.entries(def.fields)
        .map(([f, fd]) => `${f}: ${swiftType(fd.type, fd.optional)}${fd.optional ? " = nil" : ""}`)
        .join(", ");
      L.push(`  public init(${args}) {`);
      for (const f of Object.keys(def.fields)) L.push(`    self.${f} = ${f}`);
      L.push("  }");
      L.push("}\n");
    }
  }

  // Handler protocol: every request must be implemented or the shell does not compile (G4).
  L.push("/// Implement on the native side. Adding a request to the contract breaks this");
  L.push("/// protocol's conformance until handled -> contract drift is a red compile.");
  L.push("public protocol BridgeHandling: AnyObject, Sendable {");
  for (const [m, r] of Object.entries(contract.requests))
    L.push(`  func ${m}(_ params: ${r.params}) async throws -> ${r.result}`);
  L.push("}\n");

  L.push("public enum BridgeRequest: Sendable {");
  for (const [m, r] of Object.entries(contract.requests))
    L.push(`  case ${m}(${r.params})`);
  L.push("}\n");

  L.push("public struct BridgeEnvelope: Codable, Sendable {");
  L.push("  public var id: String");
  L.push("  public var method: String");
  L.push("}\n");

  L.push("public enum BridgeDecodeError: Error { case unknownMethod(String) }\n");

  L.push("public struct BridgeDispatcher: Sendable {");
  L.push("  public let handler: BridgeHandling");
  L.push("  public init(handler: BridgeHandling) { self.handler = handler }\n");
  L.push("  /// Decodes `raw` ({id, method, params}), invokes the handler, returns the");
  L.push("  /// JS to evaluate back into the surface.");
  L.push("  public func dispatch(raw: Data) async -> String {");
  L.push("    let decoder = JSONDecoder()");
  L.push("    let encoder = JSONEncoder()");
  L.push("    guard let env = try? decoder.decode(BridgeEnvelope.self, from: raw) else {");
  L.push(`      return Self.js(reply: "{\\"id\\":\\"?\\",\\"ok\\":false,\\"error\\":\\"malformed envelope\\"}")`);
  L.push("    }");
  L.push("    do {");
  L.push("      let resultJSON: Data");
  L.push("      switch env.method {");
  for (const [m, r] of Object.entries(contract.requests)) {
    L.push(`      case "${m}":`);
    L.push(`        let p = try decoder.decode(Params<${r.params}>.self, from: raw).params`);
    L.push(`        resultJSON = try encoder.encode(await handler.${m}(p))`);
  }
  L.push("      default: throw BridgeDecodeError.unknownMethod(env.method)");
  L.push("      }");
  L.push('      let body = String(data: resultJSON, encoding: .utf8) ?? "null"');
  L.push('      return Self.js(reply: "{\\"id\\":\\(Self.q(env.id)),\\"ok\\":true,\\"result\\":\\(body)}")');
  L.push("    } catch {");
  L.push('      return Self.js(reply: "{\\"id\\":\\(Self.q(env.id)),\\"ok\\":false,\\"error\\":\\(Self.q(String(describing: error)))}")');
  L.push("    }");
  L.push("  }\n");
  L.push("  struct Params<T: Decodable>: Decodable { var params: T }\n");
  for (const [e, ed] of Object.entries(contract.events)) {
    L.push(`  /// Typed native -> surface push for the \`${e}\` event.`);
    L.push(`  public static func emit${cap(e)}(_ payload: ${ed.payload}) -> String {`);
    L.push("    let body = (try? JSONEncoder().encode(payload)).flatMap { String(data: $0, encoding: .utf8) } ?? \"null\"");
    L.push(`    return "window.__${contract.bridgeName}.__event({event:\\"${e}\\",payload:\\(body)});"`);
    L.push("  }");
  }
  L.push("");
  L.push(`  static func js(reply: String) -> String { "window.__${contract.bridgeName}.__reply(\\(reply));" }`);
  L.push('  static func q(_ s: String) -> String {');
  L.push('    let escaped = s.replacingOccurrences(of: "\\\\", with: "\\\\\\\\").replacingOccurrences(of: "\\"", with: "\\\\\\"")');
  L.push('    return "\\"\\(escaped)\\""');
  L.push("  }");
  L.push(`  public static let messageHandlerName = "${contract.bridgeName}"`);
  L.push("}");
  return L.join("\n") + "\n";
}

/* ------------------------------------ TS ----------------------------------- */
function ts() {
  const L = [];
  L.push(BANNER());
  for (const [name, def] of Object.entries(contract.types)) {
    if (def.kind === "enum") {
      L.push(`export type ${name} = ${def.cases.map((c) => `"${c}"`).join(" | ")};\n`);
    } else {
      L.push(`export interface ${name} {`);
      for (const [f, fd] of Object.entries(def.fields))
        L.push(`  ${f}${fd.optional ? "?" : ""}: ${tsType(fd.type)}${fd.optional ? " | null" : ""};`);
      L.push("}\n");
    }
  }
  L.push("export interface BridgeEvents {");
  for (const [e, ed] of Object.entries(contract.events)) L.push(`  ${e}: ${ed.payload};`);
  L.push("}\n");

  L.push(`const HANDLER = "${contract.bridgeName}";`);
  L.push(`const GLOBAL = "__${contract.bridgeName}";\n`);
  L.push(`type Pending = { resolve: (v: unknown) => void; reject: (e: Error) => void };\n`);
  L.push(`class Bridge {
  #seq = 0;
  #pending = new Map<string, Pending>();
  #listeners = new Map<string, Set<(p: unknown) => void>>();
  readonly available: boolean;

  constructor() {
    const w = window as unknown as Record<string, unknown>;
    w[GLOBAL] = {
      __reply: (m: { id: string; ok: boolean; result?: unknown; error?: string }) => {
        const p = this.#pending.get(m.id);
        if (!p) return;
        this.#pending.delete(m.id);
        m.ok ? p.resolve(m.result) : p.reject(new Error(m.error ?? "bridge error"));
      },
      __event: (m: { event: string; payload: unknown }) => {
        for (const cb of this.#listeners.get(m.event) ?? []) cb(m.payload);
      },
    };
    const wk = (window as any).webkit;
    this.available = Boolean(wk?.messageHandlers?.[HANDLER]);
  }

  #call<T>(method: string, params: unknown): Promise<T> {
    if (!this.available) return Promise.reject(new Error("native bridge unavailable (running in a plain browser)"));
    const id = String(++this.#seq);
    return new Promise<T>((resolve, reject) => {
      this.#pending.set(id, { resolve: resolve as (v: unknown) => void, reject });
      (window as any).webkit.messageHandlers[HANDLER].postMessage({ id, method, params });
    });
  }

  on<K extends keyof BridgeEvents>(event: K, cb: (p: BridgeEvents[K]) => void): () => void {
    const key = event as string;
    if (!this.#listeners.has(key)) this.#listeners.set(key, new Set());
    const set = this.#listeners.get(key)!;
    set.add(cb as (p: unknown) => void);
    return () => set.delete(cb as (p: unknown) => void);
  }
`);
  for (const [m, r] of Object.entries(contract.requests)) {
    L.push(`  ${m}(params: ${r.params}): Promise<${r.result}> {`);
    L.push(`    return this.#call<${r.result}>("${m}", params);`);
    L.push("  }");
  }
  L.push("}\n");
  L.push("export const bridge = new Bridge();");
  return L.join("\n") + "\n";
}

const outputs = [
  [join(root, "shell", "Sources", "OmiShell", "Bridge.generated.swift"), swift()],
  [join(root, "surface", "src", "bridge.generated.ts"), ts()],
];

let drift = false;
for (const [path, content] of outputs) {
  const prev = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (prev === content) continue;
  drift = true;
  if (check) console.error(`drift: ${path.replace(root, ".")} is stale`);
  else writeFileSync(path, content);
}
if (check) process.exit(drift ? 1 : 0);
console.log(drift ? "bridge: regenerated" : "bridge: up to date");
