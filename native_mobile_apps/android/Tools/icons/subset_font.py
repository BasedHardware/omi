#!/usr/bin/env python3
"""Subset Material Symbols Rounded to the glyphs SFSymbols.kt uses, addressed by codepoint.

Ligatures pull every icon back in (any glyph reachable from a-z), so the app draws icons by their
private-use codepoint instead: this writes the subset font and `MaterialCodepoints.kt`.
Usage: subset_font.py  (reads Tools/fonts/material_symbols_rounded_full.ttf)
"""
import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
FULL = ROOT / "Tools/fonts/material_symbols_rounded_full.ttf"
OUT_FONT = ROOT / "design/src/main/res/font/material_symbols_rounded.ttf"
OUT_KT = ROOT / "design/src/main/kotlin/com/friend/ios/design/MaterialCodepoints.kt"
MAP = ROOT / "design/src/main/kotlin/com/friend/ios/design/SFSymbols.kt"
CODEPOINTS = ROOT / "Tools/icons/material_symbols_rounded.codepoints"

names = sorted(set(re.findall(r'SymbolGlyph\("([a-z0-9_]+)"', MAP.read_text())) | {"help"})
cps = dict(line.split() for line in CODEPOINTS.read_text().splitlines() if line.strip())
unicodes = [int(cps[n], 16) for n in names]

font = TTFont(FULL)
options = subset.Options()
options.layout_features = []
options.notdef_outline = True
options.name_IDs = ["*"]
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=unicodes)
subsetter.subset(font)
font.save(OUT_FONT)

lines = [
    "package com.friend.ios.design",
    "",
    "/** Material Symbols name -> private-use codepoint. Generated by Tools/icons/subset_font.py, do not edit. */",
    "internal val MATERIAL_CODEPOINTS: Map<String, Int> = mapOf(",
    *[f'    "{n}" to 0x{cps[n]},' for n in names],
    ")",
]
OUT_KT.write_text("\n".join(lines) + "\n")
print(f"{len(names)} glyphs, {OUT_FONT.stat().st_size // 1024} KB")
