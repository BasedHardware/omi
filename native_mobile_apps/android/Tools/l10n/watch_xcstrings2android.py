#!/usr/bin/env python3
"""omi-native Watch/Localizable.xcstrings -> wear/src/main/res/values-*/strings.xml (:wear).

The watch app has its own catalog on iOS (`watch.*` keys); the Wear OS app takes it the same way
:design takes the phone catalog (same resource names: `watch.tapToRecord` -> `watch__tapToRecord`),
with two Android adaptations:
- `%lld` (Swift Int) becomes `%d`, and the format-key suffix (`watch.omiBattery %lld`) is dropped;
- the watch talks to an Android phone, so "iPhone" reads as the locale's word for phone.

Usage: watch_xcstrings2android.py [--xcstrings PATH] [--res DIR] [--check]
"""
import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
sys.dont_write_bytecode = True
import xcstrings2android as base  # noqa: E402

DEFAULT_XC = base.CODING / "omi-native/Watch/Localizable.xcstrings"
DEFAULT_RES = base.ROOT / "wear/src/main/res"
PHONE = {"en": "phone", "de": "Handy"}


def build(xc_path: pathlib.Path) -> dict[str, str]:
    import json

    catalog = json.loads(xc_path.read_text())
    source = catalog["sourceLanguage"]
    per_locale: dict[str, dict[str, str]] = {}
    for key, entry in sorted(catalog["strings"].items()):
        name = key.split(" ")[0]
        for locale, loc in entry.get("localizations", {}).items():
            value = (loc.get("stringUnit") or {}).get("value")
            if value is None:
                continue
            value = re.sub(r"%(\d+\$)?lld", lambda m: "%" + (m.group(1) or "") + "d", value)
            value = value.replace("iPhone", PHONE.get(locale, "phone"))
            per_locale.setdefault(locale, {})[name] = value
        per_locale.setdefault(source, {}).setdefault(name, name)
    files = {}
    for locale, strings in sorted(per_locale.items()):
        folder = base.FOLDER.get(locale, f"values-{locale}")
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by Tools/l10n/watch_xcstrings2android.py from omi-native Watch/Localizable.xcstrings. Do not edit. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,ExtraTranslation,TypographyEllipsis">']
        for key, value in strings.items():
            formatted = "" if re.search(r"%(\d+\$)?[s@d]", value) else ' formatted="false"'
            lines.append(f'    <string name="{base.resource_name(key)}"{formatted}>{base.android_value(value)}</string>')
        lines.append("</resources>")
        files[f"{folder}/strings.xml"] = "\n".join(lines) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--xcstrings", type=pathlib.Path, default=DEFAULT_XC)
    ap.add_argument("--res", type=pathlib.Path, default=DEFAULT_RES)
    ap.add_argument("--check", action="store_true", help="fail when the generated files are stale")
    args = ap.parse_args()
    files = build(args.xcstrings)
    stale = []
    for rel, text in files.items():
        path = args.res / rel
        if path.exists() and path.read_text() == text:
            continue
        stale.append(rel)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check and stale:
        print(f"stale: {len(stale)} files (run Tools/l10n/watch_xcstrings2android.py)", file=sys.stderr)
        return 1
    print(f"{len(files)} locales, {'up to date' if not stale else f'{len(stale)} written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
